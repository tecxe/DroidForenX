# Root directory for forensic evidence storage. Keep evidence outside of
# static/media web-serving paths so it can never be served to the browser.
# Structure:
#   EVIDENCE_ROOT/
#     original/     read-only original evidence images (never modified)
#     acquired/     data acquired by the platform (authorized logical copies)
#     recovered/    files recovered via analysis
#     carved/       files carved from forensic images
#     working/      temporary forensic working copies during analysis
EVIDENCE_ROOT = Path(os.getenv("EVIDENCE_ROOT", str(BASE_DIR / "evidence")))

# Default marker file written inside evidence directories to protect them
# from recursive copying/traversal confusion.
EVIDENCE_MARKER = "EVIDENCE_DIR.txt"

# Maximum size (bytes) a carried/acquired file may be before processing is
# treated as "too large" during carving to avoid runaway resource use.
