"""The application's own artwork: the wordmark and the icon.

The images are generated by ``tools/make_branding.py`` and committed, so a build
never needs Pillow at the right version and the binary is reproducible. This
module is the only place that knows where they live, because that path differs
between a source checkout and a PyInstaller one-file build.

Every accessor degrades to ``None`` rather than raising: branding is decoration,
and a missing PNG must never stop the application from opening a case.
"""

from __future__ import annotations

import sys
from pathlib import Path

from PyQt6.QtCore import Qt
from PyQt6.QtGui import QIcon, QPixmap

FOLDER = Path(__file__).resolve().parent.parent / "assets" / "branding"

#: The frozen build unpacks its data under ``sys._MEIPASS``. The spec keeps the
#: repository layout inside the archive, hence the two candidates.
_FROZEN_LAYOUTS = ("desktop/assets/branding", "assets/branding")


def asset_path(name: str) -> Path | None:
    """Resolve ``name`` from the source tree or from a frozen build."""
    candidates = []
    meipass = getattr(sys, "_MEIPASS", None)
    if getattr(sys, "frozen", False) and meipass:
        candidates += [Path(meipass) / layout / name for layout in _FROZEN_LAYOUTS]
    candidates.append(FOLDER / name)

    for candidate in candidates:
        try:
            if candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def pixmap(name: str) -> QPixmap | None:
    """The named asset as a pixmap, or ``None`` when it is not shipped."""
    path = asset_path(name)
    if path is None:
        return None
    loaded = QPixmap(str(path))
    return None if loaded.isNull() else loaded


def scaled(name: str, width: int, height: int | None = None) -> QPixmap | None:
    """The named asset scaled smoothly to ``width`` (and ``height``)."""
    source = pixmap(name)
    if source is None:
        return None
    if height is None:
        height = max(1, round(source.height() * width / max(1, source.width())))
    return source.scaled(width, height, Qt.AspectRatioMode.KeepAspectRatio,
                         Qt.TransformationMode.SmoothTransformation)


def logo(width: int) -> QPixmap | None:
    return scaled("logo.png", width)


def app_icon() -> QIcon:
    """The window and taskbar icon, or an empty icon when unavailable."""
    path = asset_path("icon.png")
    if path is not None:
        return QIcon(str(path))
    ico = asset_path("icon.ico")
    return QIcon(str(ico)) if ico is not None else QIcon()


def executable_icon() -> Path | None:
    """The ``.ico`` handed to PyInstaller; ``None`` on platforms without one."""
    return asset_path("icon.ico")
