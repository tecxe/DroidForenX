"""Tests for the shipped artwork: the wordmark and the icon.

These are packaging tests as much as rendering tests. The artwork is generated by
``tools/make_branding.py`` and committed, so what can actually go wrong is a file
missing from the tree, a file missing from the frozen archive, or a widget that
silently falls back to text because the pixmap would not load. Each test below
fails on one of those.

Run with:  python -m unittest desktop.tests.test_branding -v
"""

import os
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

try:
    from PyQt6.QtWidgets import QApplication, QLabel

    from desktop.ui import branding
    from desktop.ui.main_window import MainWindow
    _QT_IMPORT = True
except Exception:  # pragma: no cover - depends on the environment
    _QT_IMPORT = False


_restore_db_path = None
_tmp_home = None


def setUpModule():
    global _restore_db_path, _tmp_home
    from desktop.core import database

    _restore_db_path = database.DB_PATH
    _tmp_home = tempfile.mkdtemp(prefix="dfx-branding-")
    database.DB_PATH = Path(_tmp_home) / "droidforenx.db"


def tearDownModule():
    from desktop.core import database

    if _restore_db_path is not None:
        database.DB_PATH = _restore_db_path
    if _tmp_home:
        shutil.rmtree(_tmp_home, ignore_errors=True)


def _make_qapp():
    if not _QT_IMPORT:
        return None
    app = QApplication.instance() or QApplication([])
    app.setOrganizationName("DroidForenXTests")
    app.setApplicationName("DroidForenXTests")
    return app


def _pump(app, rounds=4):
    for _ in range(rounds):
        app.processEvents()


class BrandingAssetsTest(unittest.TestCase):
    """The files themselves, independent of any window."""

    EXPECTED = ("logo.png", "icon.png", "icon.ico")

    @classmethod
    def setUpClass(cls):
        # QPixmap needs a QGuiApplication; creating one without it aborts the
        # process rather than raising, so it has to happen before any load.
        cls._app = _make_qapp()

    def test_every_expected_asset_is_committed(self):
        for name in self.EXPECTED:
            path = branding.asset_path(name)
            self.assertIsNotNone(path, f"{name} is not in {branding.FOLDER}")
            self.assertGreater(path.stat().st_size, 1024, f"{name} looks truncated")

    def test_the_executable_icon_is_a_real_multi_size_ico(self):
        path = branding.executable_icon()
        if path is None:
            self.skipTest("no .ico on this platform")

        # An .ico starts with a 6-byte header: reserved, type (1 = icon), count.
        with open(path, "rb") as handle:
            header = handle.read(6)
        self.assertEqual(header[:2], b"\x00\x00")
        self.assertEqual(int.from_bytes(header[2:4], "little"), 1)
        self.assertGreaterEqual(int.from_bytes(header[4:6], "little"), 5,
                                "single-size icons render badly in Explorer")

    def test_the_wordmark_is_two_times_its_display_width(self):
        # The sidebar asks for 168 px; a 1x asset would be soft on a HiDPI panel.
        path = branding.asset_path("logo.png")
        if path is None:
            self.fail("logo.png missing")

        from PyQt6.QtGui import QPixmap
        logo = QPixmap(str(path))
        self.assertFalse(logo.isNull())
        self.assertGreaterEqual(logo.width(), 336)

    @unittest.skipUnless(_QT_IMPORT, "PyQt6 is not available")
    def test_pixmaps_load_and_scale(self):
        logo = branding.logo(168)
        self.assertIsNotNone(logo)
        self.assertAlmostEqual(logo.width(), 168, delta=1)
        self.assertGreater(logo.height(), 8)

    @unittest.skipUnless(_QT_IMPORT, "PyQt6 is not available")
    def test_a_missing_asset_returns_none_instead_of_raising(self):
        self.assertIsNone(branding.pixmap("does-not-exist.png"))
        self.assertIsNone(branding.scaled("does-not-exist.png", 10))

    @unittest.skipUnless(_QT_IMPORT, "PyQt6 is not available")
    def test_the_frozen_layout_is_probed_before_the_source_tree(self):
        # The one-file build unpacks to _MEIPASS and has no repository around it,
        # so the lookup has to look there first. Simulate it rather than trusting
        # the spec's data list.
        meipass = tempfile.mkdtemp(prefix="dfx-meipass-")
        target = Path(meipass) / "desktop" / "assets" / "branding"
        target.mkdir(parents=True)
        (target / "logo.png").write_bytes(
            (branding.FOLDER / "logo.png").read_bytes())
        try:
            old_meipass = getattr(sys, "_MEIPASS", None)
            old_frozen = getattr(sys, "frozen", None)
            sys._MEIPASS = meipass
            sys.frozen = True
            resolved = branding.asset_path("logo.png")
            self.assertIsNotNone(resolved)
            self.assertEqual(resolved.parent, target)
        finally:
            if old_meipass is None:
                del sys._MEIPASS
            else:
                sys._MEIPASS = old_meipass
            if old_frozen is None:
                del sys.frozen
            else:
                sys.frozen = old_frozen
            shutil.rmtree(meipass, ignore_errors=True)


@unittest.skipUnless(_QT_IMPORT, "PyQt6 is not available")
class BrandingInTheWindowTest(unittest.TestCase):
    """The artwork as the operator actually sees it."""

    @classmethod
    def setUpClass(cls):
        cls._app = _make_qapp()
        cls.window = MainWindow()
        cls.window.resize(1280, 800)
        cls.window.show()
        _pump(cls._app)

    @classmethod
    def tearDownClass(cls):
        cls.window.close()
        cls.window.deleteLater()
        _pump(cls._app)

    def test_the_sidebar_shows_the_wordmark_instead_of_text(self):
        label = getattr(self.window, "logo_label", None)
        self.assertIsNotNone(label, "the wordmark label was not built")
        self.assertIsInstance(label, QLabel)
        self.assertIsNotNone(label.pixmap())
        self.assertFalse(label.pixmap().isNull())

    def test_the_wordmark_fits_the_sidebar(self):
        label = self.window.logo_label
        sidebar = self.window.sidebar
        self.assertLessEqual(label.width(), sidebar.width(),
                             "the logo is wider than the column it sits in")
        self.assertLessEqual(label.height(), 120)

    def test_the_window_carries_the_icon(self):
        self.assertFalse(self.window.windowIcon().isNull())
        self.assertFalse(self.window.windowIcon().pixmap(64, 64).isNull())
